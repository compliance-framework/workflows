package pluginhealth

import (
	"encoding/json"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"time"
)

// State is what a run keeps in the issue body for the next one: the deprecation candidates it
// reported, and the most recently closed train issue when it ran.
type State struct {
	Candidates []string `json:"candidates"`
	Train      int      `json:"train"`
}

var stateLine = regexp.MustCompile(`(?m)^<!-- plugin-health (\{.*\}) -->$`)

// ParseState reads the State of an issue body; ok is false when there is none.
func ParseState(body string) (State, bool) {
	m := stateLine.FindStringSubmatch(body)
	var s State
	if m == nil || json.Unmarshal([]byte(m[1]), &s) != nil {
		return State{}, false
	}
	return s, true
}

// Header is the context line above the table.
type Header struct {
	Manifest string
	Batches  []int
	Run      string // the run's URL, or ""
	Docs     string // the status rules' URL
	Now      time.Time
}

// Markdown renders the report: the state marker, a context line and the table.
func Markdown(r Report, s State, h Header) string {
	if s.Candidates == nil {
		s.Candidates = []string{}
	}
	state, _ := json.Marshal(s)
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- plugin-health %s -->\n", state)
	by := "plugin-health"
	if h.Run != "" {
		by = "[plugin-health](" + h.Run + ")"
	}
	fmt.Fprintf(&b, "Regenerated by %s on %s from `%s` (active batches %v). Latest %s final release: **%s**. "+
		"Status rules: [docs/plugin-health.md](%s).\n\n",
		by, h.Now.UTC().Format("2006-01-02 15:04 UTC"), h.Manifest, h.Batches, r.AgentRepo, r.Agent, h.Docs)
	b.WriteString("| Plugin | Agent library | Minors behind | Protocol | Last ccf-bump | Last release | Status | Notes |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, row := range r.Rows {
		notes := append(slices.Clone(row.Notes), row.Errors...)
		fmt.Fprintf(&b, "| [%s](https://github.com/%s/%s) | %s | %s | %s | %s | %s | %s | %s |\n",
			row.Repo, r.Owner, row.Repo, orDash(row.Lib), behind(row.Behind), protocolCell(row.Protocol),
			bumpCell(row.Bump), releaseCell(row.Release), row.Status, cell(strings.Join(notes, "; ")))
	}
	if c := r.Candidates(); len(c) > 0 {
		fmt.Fprintf(&b, "\nDeprecation candidates: %s.\n", strings.Join(c, ", "))
	}
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "–"
	}
	return cell(s)
}

// cell keeps a value on one table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}

func behind(n int) string {
	switch {
	case n < 0:
		return "–"
	case n >= OlderMajor:
		return "older major"
	}
	return fmt.Sprint(n)
}

func protocolCell(p int) string {
	switch p {
	case -1:
		return "–"
	case 0:
		return "unset"
	}
	return fmt.Sprintf("v%d", p)
}

func bumpCell(p *BumpPR) string {
	if p == nil {
		return "none"
	}
	s := p.Result()
	if !p.Merged.IsZero() {
		s += " " + p.Merged.UTC().Format(time.DateOnly)
	}
	return fmt.Sprintf("%s ([#%d](%s))", s, p.Number, p.URL)
}

func releaseCell(r *Release) string {
	if r == nil {
		return "none"
	}
	return fmt.Sprintf("%s (%s)", cell(r.Tag), r.Date.UTC().Format(time.DateOnly))
}

// Changed reports whether two candidate lists differ, ignoring order.
func Changed(before, after []string) bool {
	a, b := slices.Sorted(slices.Values(before)), slices.Sorted(slices.Values(after))
	return !slices.Equal(a, b)
}

// SlackMessage is the #ccf-releases post for a changed candidate list.
func SlackMessage(before, after []string, issueURL string) string {
	var added, removed []string
	for _, c := range after {
		if !slices.Contains(before, c) {
			added = append(added, c)
		}
	}
	for _, c := range before {
		if !slices.Contains(after, c) {
			removed = append(removed, c)
		}
	}
	now := "none"
	if len(after) > 0 {
		now = strings.Join(after, ", ")
	}
	msg := ":warning: Plugin deprecation candidates changed. Now: " + now + "."
	if len(added) > 0 {
		msg += " Added: " + strings.Join(added, ", ") + "."
	}
	if len(removed) > 0 {
		msg += " No longer: " + strings.Join(removed, ", ") + "."
	}
	return msg + " <" + issueURL + "|Plugin health>"
}
